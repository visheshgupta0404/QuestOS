/** Available quest realm modules in QuestOS. */
export type Module = 'inbox' | 'files';

/** Represents a candidate Gmail message or sample message in an inbox quest. */
export type Message = {
  /** Unique message identifier. */
  id: string;
  /** Subject line of the email. */
  subject: string;
  /** Sender email address or display name. */
  from: string;
  /** ISO date string or header date of the email. */
  date: string;
  /** List of Gmail labels currently assigned to the message. */
  labels: string[];
};

/** User or suggested decision for a candidate message. */
export type Decision = {
  /** Target message identifier. */
  id: string;
  /** The action to perform: archive (remove INBOX), label (add QuestOS/Cleared), or keep (no changes). */
  action: 'archive' | 'label' | 'keep';
};

/** A validated, bounded quest plan containing candidate messages to be reviewed and approved. */
export type Plan = {
  /** Unique plan identifier. */
  id: string;
  /** Candidate messages included in this quest batch. */
  messages: Message[];
  /** ISO timestamp when the plan was created. */
  createdAt: string;
  /** ISO timestamp when the plan expires (typically 15 minutes after scan). */
  expiresAt: string;
};

/** Durable execution receipt recording verified cleanup actions, XP awarded, and undo status. */
export type Receipt = {
  /** Unique receipt identifier (matches plan ID for execution). */
  id: string;
  /** Realm module that generated this receipt. */
  module: Module;
  /** Display title for the quest run. */
  title: string;
  /** Total number of items affected. */
  count: number;
  /** Total experience points awarded. */
  xp: number;
  /** ISO timestamp when the receipt was created. */
  createdAt: string;
  /** Current lifecycle status of the execution. */
  status: 'verified' | 'undone' | 'partial' | 'failed' | 'executing' | 'undoing';
  /** Operating mode under which this quest was executed. */
  mode: 'demo' | 'live' | 'local';
  /** Human-readable explanation and audit trail details. */
  detail: string;
  /** Whether this receipt can currently be undone. */
  canUndo?: boolean;
  /** Optional record of the exact decisions executed. */
  decisions?: Decision[];
};

/** Gamified story briefing generated by Gemini or deterministic fallback rules. */
export type QuestStory = {
  /** Narrative quest title. */
  title: string;
  /** Story context and instructions for the user. */
  briefing: string;
  /** Completion fanfare message. */
  victory: string;
  /** Narrative generation source. */
  source: 'gemini' | 'rules';
};

/** Analyzed file entry for File Forest duplicate detection and organization. */
export type FileEntry = {
  /** Client-side temporary unique ID. */
  id: string;
  /** Browser File object reference. */
  file: File;
  /** SHA-256 hex digest of file contents. */
  hash: string;
  /** Categorized target directory folder name. */
  category: string;
  /** If this file is an exact duplicate, the ID of the canonical first file. */
  duplicateOf?: string;
  /** Output relative destination path inside the organized ZIP. */
  path: string;
};

/** System and third-party integration connection status. */
export type IntegrationStatus = {
  /** Whether the server has required configuration keys. */
  configured: boolean;
  /** Whether a valid user session is authenticated. */
  connected: boolean;
  /** Connected user email if available. */
  email?: string;
  /** Whether Gemini AI generation is configured. */
  ai: boolean;
  /** Whether persistent storage is operational. */
  storage: boolean;
  /** Configured storage backend provider. */
  storageProvider?: 'local' | 'supabase';
  /** List of missing setup items or configuration notices. */
  missing: string[];
};
